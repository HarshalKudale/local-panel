/**
 * Theme definitions for Local Panel.
 * Each theme provides all CSS custom properties used by the app.
 */

export type ThemeMode = "dark" | "light";

export interface ThemeDef {
    id: string;
    name: string;
    mode: ThemeMode;
    /** Electron titlebar overlay */
    overlay: { color: string; symbolColor: string };
    /** CSS custom properties (without leading --) */
    vars: Record<string, string>;
    /** Enables global "Terminal CLI" chrome: monospace everywhere, 0 radius, scanlines, phosphor glow */
    terminal?: boolean;
}

